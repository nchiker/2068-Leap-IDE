"use strict";
// gen-font.mjs -- generates arcade/runtime/v1/font.inc, the Leap Arcade runtime's 96-glyph 8x8 font (codes 32..127), from the
// Leap V2 font table FONT_TABLE in ~/2068-Leap/kernel/graphics/graphics.asm (GENERATED; never hand-edit font.inc).
//   node arcade/tools/gen-font.mjs [path-to-graphics.asm]
// Leap's table has 95 glyphs (printable ASCII 32..126, in Leap's own order: space, digits, A-Z [ \ ] ^ _ `, a-z { | } ~,
// then the punctuation); each glyph is preceded by a comment "; 'c'" naming its character, which is what this reads.
// Code 127 has no glyph in Leap ("0-31 and 127: not found" in GFX_CHAR_TO_FONT_OFFSET), so it is drawn blank here too.
import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
export const LEAP_FONT_SRC = join(homedir(), '2068-Leap/kernel/graphics/graphics.asm');

/** @returns {Map<number, number[]>} char code -> 8 bytes, from the FONT_TABLE block of Leap's graphics.asm */
export function readLeapFont(file = LEAP_FONT_SRC) {
  const lines = readFileSync(file, 'utf8').split('\n');
  const start = lines.findIndex((l) => /^FONT_TABLE:/.test(l));
  if (start < 0) throw new Error('FONT_TABLE not found in ' + file);
  const glyphs = new Map();
  let ch = null;
  for (let i = start + 1; i < lines.length; i++) {
    const l = lines[i];
    if (/^[A-Z_0-9]+:/.test(l)) break;                       // next label: the table is over
    let m = l.match(/^\s*;\s*'(.)'/);
    if (m) { ch = m[1].charCodeAt(0); continue; }
    m = l.match(/^\s*DB\s+(.*)$/);
    if (m && ch !== null) {
      const bytes = m[1].split(';')[0].split(',').map((s) => parseInt(s.trim().replace('$', ''), 16));
      if (bytes.length !== 8 || bytes.some((b) => !(b >= 0 && b <= 255))) throw new Error('bad glyph line: ' + l);
      if (glyphs.has(ch)) throw new Error('duplicate glyph ' + ch);
      glyphs.set(ch, bytes);
      ch = null;
    }
  }
  for (let c = 32; c <= 126; c++) if (!glyphs.has(c)) throw new Error('missing glyph for code ' + c);
  if (glyphs.size !== 95) throw new Error('expected 95 glyphs, got ' + glyphs.size);
  return glyphs;
}

export function fontInc(glyphs, src) {
  const out = [
    '; font.inc -- GENERATED by arcade/tools/gen-font.mjs; never hand-edit.',
    `; Source: ${src.replace(homedir(), '~')} (FONT_TABLE, the Leap V2 font; 95 glyphs for codes 32..126, 8 bytes each, bit 7 = leftmost`,
    '; pixel).  Code 127 has no glyph in Leap and is blank here.  96 glyphs x 8 bytes = 768 bytes; glyph n is code 32+n.',
    'FONT_GLYPHS:',
  ];
  for (let c = 32; c <= 127; c++) {
    const g = glyphs.get(c) ?? [0, 0, 0, 0, 0, 0, 0, 0];
    const name = c === 127 ? 'DEL (blank)' : c === 32 ? 'space' : String.fromCharCode(c);
    out.push(`    DB ${g.map((b) => '$' + b.toString(16).toUpperCase().padStart(2, '0')).join(', ')}   ; ${c} ${name}`);
  }
  return out.join('\n') + '\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const src = process.argv[2] ?? LEAP_FONT_SRC;
  const g = readLeapFont(src);
  writeFileSync(join(HERE, '../runtime/v1/font.inc'), fontInc(g, src));
  console.log('wrote arcade/runtime/v1/font.inc (95 glyphs from ' + src + ')');
}
