"use strict";
// build-runtime-v2ink.mjs -- the separate v2 runtime build WITH classic-scene sprite ink (docs/ARCADE_STUDIO_COMPLETION_CONTRACT.md "SC"):
// the same sources as build-runtime-v2.mjs assembled with -DSPRITE_INK (spritecol.asm, RT_SPRITEINK).  The default v2 build stays byte-identical.
//   node arcade/tools/build-runtime-v2ink.mjs     builds, prints the usage
// Writes into arcade/build/v2ink/:  runtime.bin, runtime.json ({ version: 2, variant: 'ink', symbols, constants, image }), runtime.inc, .sym, .lst, .dck
// Importable:  buildRuntimeInk() -> { img, syms, usage, dck, json };  assembleGameInk(asmFile, opts);  linkGame / dckOf are the v2 ones.
import { readFileSync, writeFileSync, mkdirSync, renameSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { RUNTIME_DIR, CONSTANTS, SHIPPED_CHUNKS, readSyms, linkGame, dckOf, printUsage } from './build-runtime-v2.mjs';
export { linkGame, dckOf };

const HERE = dirname(fileURLToPath(import.meta.url));
export const OUT = join(HERE, '../build/v2ink');
const WORK = join(OUT, 'work');
let tmpCounter = 0;
function writeAtomic(file, data) { const tmp = `${file}.tmp-${process.pid}-${tmpCounter++}`; writeFileSync(tmp, data); renameSync(tmp, file); }
function sjasm(args, cwd) {
  try { execFileSync('sjasmplus', args, { cwd, stdio: ['ignore', 'pipe', 'pipe'] }); }
  catch (e) { throw new Error('sjasmplus failed:\n' + (e.stdout || '') + (e.stderr || '')); }
}
function chunkUsage(syms) {
  const mods = [];
  for (const k of Object.keys(syms)) {
    const m = k.match(/^M_(\w+)_S$/);
    if (m && syms[`M_${m[1]}_E`] !== undefined) mods.push({ name: m[1].toLowerCase(), from: syms[k], to: syms[`M_${m[1]}_E`] });
  }
  mods.sort((a, b) => a.from - b.from);
  const per = {};
  for (const c of SHIPPED_CHUNKS) per[c] = 0;
  for (const mod of mods) { mod.size = mod.to - mod.from; for (let a = mod.from; a < mod.to; a++) per[a >> 13] = (per[a >> 13] ?? 0) + 1; }
  return { mods, per };
}

export function buildRuntimeInk({ quiet = true } = {}) {
  const tag = process.env.ARCADE_JOB_TAG;
  const work = tag ? join(WORK, 'rt-' + tag) : WORK;
  mkdirSync(work, { recursive: true });
  const lstFile = join(work, 'runtime.lst'), symFile = join(work, 'runtime.sym');
  sjasm(['--nologo', '-DSPRITE_INK', `--lst=${lstFile}`, `--sym=${symFile}`, `-I${RUNTIME_DIR}`, join(RUNTIME_DIR, 'runtime.asm')], work);
  const img = new Uint8Array(readFileSync(join(work, 'mem.bin')));
  const all = readSyms(symFile);
  const syms = {};
  for (const [k, v] of Object.entries(all)) if (!k.includes('.') && !/^M_\w+_[SE]$/.test(k)) syms[k] = v;
  if (syms.RT_SPRITEINK === undefined) throw new Error('RT_SPRITEINK missing from the ink build');
  const constants = {};
  for (const k of CONSTANTS) { if (all[k] === undefined) throw new Error('missing constant ' + k); constants[k] = all[k]; }
  const json = { version: 2, variant: 'ink', symbols: syms, constants, image: 'runtime.bin' };
  writeAtomic(join(OUT, 'runtime.bin'), img);
  writeAtomic(join(OUT, 'runtime.json'), JSON.stringify(json, null, 2) + '\n');
  writeAtomic(join(OUT, 'runtime.sym'), readFileSync(symFile));
  writeAtomic(join(OUT, 'runtime.lst'), readFileSync(lstFile));
  const inc = ['; runtime.inc -- GENERATED by arcade/tools/build-runtime-v2ink.mjs (the sprite-ink build); never hand-edit.']
    .concat(Object.entries(syms).map(([k, v]) => `${k} EQU $${v.toString(16).toUpperCase().padStart(4, '0')}`));
  writeAtomic(join(OUT, 'runtime.inc'), inc.join('\n') + '\n');
  const dck = dckOf(img);
  writeAtomic(join(OUT, 'runtime.dck'), dck);
  const usage = chunkUsage(all);
  if (!quiet) printUsage(usage, dck);
  return { img, syms: all, usage, dck, json };
}

/** A hand-written test game assembled against the ink build's runtime.inc (its addresses differ from the default build's). */
export function assembleGameInk(asmFile, { name = basename(asmFile, '.asm'), defines = {} } = {}) {
  const dir = join(WORK, 'game-' + name);
  mkdirSync(dir, { recursive: true });
  const args = ['--nologo', `--lst=${join(dir, 'game.lst')}`, `--sym=${join(dir, 'game.sym')}`, `-I${OUT}`, `-I${RUNTIME_DIR}`];
  for (const [k, v] of Object.entries(defines)) args.push(`-D${k}=${v}`);
  args.push(asmFile);
  sjasm(args, dir);
  return { bytes: new Uint8Array(readFileSync(join(dir, 'game.bin'))), syms: readSyms(join(dir, 'game.sym')) };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) buildRuntimeInk({ quiet: false });
