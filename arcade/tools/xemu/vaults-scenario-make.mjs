#!/usr/bin/env node
"use strict";
// vaults-scenario-make.mjs -- (re)generate vaults-scenario.json, the input of the Vaults cross-emulator check.
//   node arcade/tools/xemu/vaults-scenario-make.mjs
// The first PREFIX ticks are the first PREFIX ticks of the recorded LOSE run (tests/arcade-m8-vaults-script.mjs: the title, fire on tick 15, the game from tick 18,
// turning and walking through the maze to the south-east).  The rest is worked out CLOSED-LOOP once on TSRun: the player turns towards wraith 4 (the one that wakes and
// comes) and fires while it is in front of him, until it is dead, then walks on a few ticks.  What the loop chose (one stick value per tick) is written out; every
// emulator then plays exactly that list open-loop (the game is deterministic given its input per tick), so the loop's use of TSRun's memory does not matter to the comparison.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LOSE_RUNS } from '../../../tests/arcade-m8-vaults-script.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ARCADE = resolve(HERE, '../..');
// ticks whose state and screen are compared byte by byte: the title (5, 12), the fire edge and the start of the game (15-20), turning and walking (30-175), shots and the kill (183-201), after
const SAMPLES = [5, 12, 15, 16, 17, 18, 19, 20, 30, 45, 60, 80, 100, 130, 160, 175, 183, 184, 190, 197, 198, 199, 200, 201, 205, 230, 250];
const PREFIX = Number(process.argv[2] ?? 178), MAXT = 250;
const rle = (a) => { const r = []; for (const v of a) { if (r.length && r.at(-1)[0] === v) r.at(-1)[1]++; else r.push([v, 1]); } return r; };
const prefix = []; for (const [v, n] of LOSE_RUNS) for (let i = 0; i < n && prefix.length < PREFIX; i++) prefix.push(v);

// the TSRun module reads the scenario file at import: write a placeholder first
writeFileSync(join(HERE, 'vaults-scenario.json'), JSON.stringify({ runs: [[0, MAXT]], sample_ticks: [], last_tick: MAXT }));
const T = await import('./vaults-tsrun.mjs');
const mt = T.meta();
const m = T.newMachine(join(ARCADE, 'build/vaults.dck'));
const sg = (v) => ((v & 0xFFFF) ^ 0x8000) - 0x8000;
const rd = (a) => sg(m.ram[a] | (m.ram[a + 1] << 8));
const arr = (n, i) => rd(mt.arrays[n].addr + 2 * i);
const out = prefix.slice();
const script = out;   // T.stickAt reads T.script: drive input directly instead
const feed = (t) => { const sv = out[t] ?? 0; for (let r = 0; r < 8; r++) m.keyMatrix[r] = 0x1F; for (const [name, bit] of Object.entries(T.STICK)) if (sv & bit) { const [row, b] = T.KEYS[name]; m.keyMatrix[row] &= ~(1 << b); } };
const WRAITH = 4;
let killedAt = -1;
feed(0);
T.run(m, {
  lastTick: MAXT,
  onTick(mm, t) {
    // decide the input for index t (the FRAME call that runs next)
    if (t >= out.length) {
      let sv = 0;
      if (killedAt < 0) {
        const dx = arr('EX', WRAITH) - rd(mt.vars.PX), dy = arr('EY', WRAITH) - rd(mt.vars.PY);
        const want = Math.round(Math.atan2(dy, dx) / (2 * Math.PI) * 256) & 255;
        const diff = ((want - rd(mt.vars.PA) + 128) & 255) - 128;
        if (diff > 3) sv |= T.STICK.RIGHT; else if (diff < -3) sv |= T.STICK.LEFT;
        if (Math.abs(diff) <= 6) sv |= T.STICK.FIRE;
        if (arr('EH', WRAITH) === 0) killedAt = t;
      } else if (t - killedAt < 3) sv = 0;
      else sv = T.STICK.UP;
      out.push(sv);
    }
    feed(t);
  },
});
while (out.length > MAXT) out.pop();
const lastTick = out.length;
console.error(`prefix ${PREFIX}, ${lastTick} ticks, wraith 4 killed at call index ${killedAt}`);
writeFileSync(join(HERE, 'vaults-scenario.json'), JSON.stringify({ comment: 'Generated by vaults-scenario-make.mjs. runs: the stick value of every FRAME call, [value, ticks]; joystick 1 bits 1 up, 2 down, 4 left, 8 right, 16 fire.', prefix: PREFIX, runs: rle(out), sample_ticks: SAMPLES.filter((n) => n <= lastTick), last_tick: lastTick }, null, 1));
