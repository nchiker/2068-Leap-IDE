#!/usr/bin/env node
"use strict";
// runner-scenario-make.mjs -- (re)generate runner-scenario.json, the input of the Leap Runner cross-emulator check.
//   node arcade/tools/xemu/runner-scenario-make.mjs [LEVELS]      LEVELS = how many level changes the scenario plays (default 2: level 1 -> 2 -> 3)
// The input is the recorded play-through of arcade/examples/runner.arc (arcade/examples/runner.script.json, made by tests/arcade-runner.mjs --record: the title, fire on tick 14,
// then each level to its flag), cut a few ticks after the LEVELS-th level change has loaded its world.  `runs` is the stick value of every FRAME call, run-length coded [value, ticks]
// (joystick 1 bits: 1 up, 4 left, 8 right, 16 fire); index t is what the FRAME call made when V_TICKS = t reads.  The sample ticks (state compared byte by byte on top of the screens
// of every tick) are worked out on the reference interpreter: the title, the start of each level, the tick the flag is reached, the message (ticks +1 .. +4), the tick that loads the
// next world through the window (the long one), the two after it, and some ticks of the new level.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from '../../../src/lang/arcade/arcade-parse.js';
import { interpret } from '../../../src/lang/arcade/arcade-interp.js';

const HERE = dirname(fileURLToPath(import.meta.url));
const ARCADE = resolve(HERE, '../..');
const LEVELS = Number(process.argv[2] ?? 2);
const src = readFileSync(join(ARCADE, 'examples/runner.arc'), 'utf8');
const assets = JSON.parse(readFileSync(join(ARCADE, 'examples/runner.assets.json'), 'utf8'));
const rec = JSON.parse(readFileSync(join(ARCADE, 'examples/runner.script.json'), 'utf8'));
const full = []; for (const [v, n] of rec.runs) for (let i = 0; i < n; i++) full.push(v);
const rle = (a) => { const r = []; for (const v of a) { if (r.length && r.at(-1)[0] === v) r.at(-1)[1]++; else r.push([v, 1]); } return r; };

const ticks = interpret(parse(src).ast, { version: 3, ticks: full.length, assets, stick: (t) => full[t - 1] ?? 0, maxSteps: 4e9 }).ticks.map((x) => x.vars);
// V_TICKS = n is the state after n calls = ticks[n - 1]
const at = (n) => ticks[n - 1];
const begin = (l) => ticks.findIndex((v) => v.ST === 1 && v.LV === l) + 1;           // the call that starts level l (BEGINLEVEL ran in it)
const flag = (l) => ticks.findIndex((v, k) => v.ST === 4 && v.NL === l + 1 && (k === 0 || ticks[k - 1].ST === 1)) + 1;
const last = begin(LEVELS) + 30;
const samples = new Set([5, 12, 14, 15, 16, 18, 20, 22]);
for (let l = 0; l <= LEVELS; l++) {
  const b = begin(l);
  for (const d of [-1, 0, 1, 2, 10, 30]) samples.add(b + d);
  if (l < LEVELS) {
    const f = flag(l);
    for (const d of [-40, -1, 0, 1, 2, 3, 4, 5, 20, 35, 36, 37, 38]) samples.add(f + d);      // the flag, "LEVEL n" going up, and the ticks around the world load (f + 37 is the long one)
    for (let k = 1; k <= 5; k++) samples.add(Math.round(b + (f - b) * k / 6));              // along the level
  }
}
const sampleTicks = [...samples].filter((t) => t >= 1 && t <= last).sort((a, b) => a - b);
const out = full.slice(0, last);
writeFileSync(join(HERE, 'runner-scenario.json'), JSON.stringify({
  comment: 'Generated by runner-scenario-make.mjs from arcade/examples/runner.script.json. runs: the stick value of every FRAME call, [value, ticks]; joystick 1 bits 1 up, 4 left, 8 right, 16 fire (up and fire are played as the SPACE key).',
  levels: LEVELS, runs: rle(out), sample_ticks: sampleTicks, last_tick: last, events: { begin: Array.from({ length: LEVELS + 1 }, (_, l) => begin(l)), flag: Array.from({ length: LEVELS }, (_, l) => flag(l)) } }, null, 1) + '\n');
console.error(`${last} ticks, ${LEVELS} level changes (flags at ${Array.from({ length: LEVELS }, (_, l) => flag(l))}, levels begin at ${Array.from({ length: LEVELS + 1 }, (_, l) => begin(l))}), ${sampleTicks.length} sampled ticks; state at the last: ST ${at(last).ST} LV ${at(last).LV} PX ${at(last).PX}`);
