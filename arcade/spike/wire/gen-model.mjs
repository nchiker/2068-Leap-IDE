"use strict";
// Wireframe spike: a "compiled model" -- the rotation code a compiler would emit for a model it knows at compile time.
// The model's coordinates are constants, so each product (matrix entry x coordinate value) is computed once per object
// for every distinct |value| on each axis, and every vertex is a sum of up to three stored products (zeros vanish,
// signs become add / subtract). Same arithmetic as project_full (exact products, (sum + 32) >> 6), so the same result.
import { writeFileSync } from 'node:fs';

/** pts: [[x,y,z]...] int8 (|c| <= 64). Writes `file` with the routine `project_model` (uses PROD as scratch). */
export function genModel(pts, file) {
  const vals = [0, 1, 2].map(a => [...new Set(pts.map(p => Math.abs(p[a])).filter(v => v))].sort((p, q) => p - q));
  const slot = new Map();                          // key "row,axis,value" -> PROD offset
  const L = [];
  const e = s => L.push('    ' + s);
  L.push('; GENERATED by gen-model.mjs -- the rotation of one fixed model; do not edit');
  L.push(`; ${pts.length} vertices; distinct |x| ${vals[0].join(' ')}; |y| ${vals[1].join(' ')}; |z| ${vals[2].join(' ')}`);
  L.push('project_model:');
  e('ld h,QSL>>8');
  for (let r = 0; r < 3; r++) for (let a = 0; a < 3; a++) {
    if (!vals[a].length) continue;
    e(`ld a,(MAT+${3 * r + a})`); e('ld b,a');
    for (const v of vals[a]) {
      const off = 2 * slot.size; slot.set(`${r},${a},${v}`, off);
      e(`ld c,${v}`); e('TERMLD'); e(`ld (PROD+${off}),de`);
    }
  }
  pts.forEach((p, i) => {
    L.push(`; vertex ${i}: ${p.join(', ')}`);
    for (let r = 0; r < 3; r++) {
      const terms = [0, 1, 2].filter(a => p[a]).map(a => ({ off: slot.get(`${r},${a},${Math.abs(p[a])}`), neg: p[a] < 0 }));
      terms.sort((t, u) => t.neg - u.neg);       // a positive term first when there is one
      if (!terms.length) e('ld hl,0');
      else if (!terms[0].neg) e(`ld hl,(PROD+${terms[0].off})`);
      else { e('ld hl,0'); e(`ld de,(PROD+${terms[0].off})`); e('or a'); e('sbc hl,de'); }
      for (const t of terms.slice(1)) { e(`ld de,(PROD+${t.off})`); if (t.neg) { e('or a'); e('sbc hl,de'); } else e('add hl,de'); }
      e('ex de,hl'); e(`RNDADD ${['TX', 'TY', 'TZ'][r]}`); e(`ld (${['P_CX', 'P_CY', 'P_CZ'][r]}),hl`);
    }
    e('call proj_point'); e('ld hl,PIDX'); e('inc (hl)');
  });
  e('ret');
  L.push('project_model_end:');
  writeFileSync(file, L.join('\n') + '\n');
  return { products: slot.size };
}
