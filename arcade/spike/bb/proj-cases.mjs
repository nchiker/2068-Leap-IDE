"use strict";
// proj-cases.mjs -- B1 (docs/ARCADE_BILLBOARDS_CONTRACT.md section 5): every projection path, before (KERNEL 3, proj.asm: the v4 code before B1)
// against after (KERNEL 4, proj-b1.asm around the live arcade/runtime/v4/raybb.asm), T-states of ray_bb with ONE instance, the multiplies kept
// (the second call of a pose), grouped by the case and the signs of dx, dy, cs, sn; then multi-instance scenes (the sort).  Every run is checked
// against the reference (ref.mjs: R_BN, the records of the drawable instances, RAY_BLIST).
//   node arcade/spike/bb/proj-cases.mjs [samples (default 40000)]
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { HERE, assemble, newMachine, callAt, poke16, peek16 } from './lib.mjs';
import * as R from './ref.mjs';

const ROOT = join(HERE, '../../..');
const src = readFileSync(join(ROOT, 'arcade/runtime/v4/raybb.asm'), 'utf8');
writeFileSync(join(HERE, 'proj-rt.asm'), '; GENERATED by run-bb.mjs from arcade/runtime/v4/raybb.asm: do not edit\n' + src.slice(src.indexOf('; ray_bb:'), src.indexOf('; bb_draw:')));
const K = { old: assemble({ KERNEL: 3 }), new: assemble({ KERNEL: 4 }) };
const FRAMES = 0x8800;
const rr = R.rng(Number(process.env.SEED ?? 777));
// two asset sets of 8 (AST + 16 i must stay in its page: 8 assets), chosen per sample
const POOLS = [[[16, 1], [8, 2], [24, 4], [8, 8], [16, 16], [32, 32], [16, 48], [24, 13]], [[8, 3], [16, 24], [8, 5], [16, 6], [16, 12], [8, 40], [24, 7], [32, 31]]]
  .map((sz, pi) => sz.map(([w, h], id) => ({ ...R.normAsset(R.randomAsset(rr, w, h, 1, 3)), id: `p${pi}.${id}` })));
let assets = POOLS[0];
let bad = 0;
const fails = [];

function run(P, insts, pose, mw, mh) {
  const S = P.sym, m = newMachine(P);
  for (let n = 0; n < 512; n++) poke16(m, 0xC300 + 2 * n, R.RECIP[n]);
  m.ram.set(R.HGT, 0xC700);
  m.ram[0x5D00] = 0xEE; m.ram[0x5D01] = 2; m.ram[0x5D2E] = 0xEE; m.ram[0x5D2F] = 2;
  let fa = FRAMES;
  const addr = [];
  assets.forEach((a, ai) => {
    const b = 0xD680 + 16 * ai, bytes = []; for (const f of a.frames) for (const row of f) bytes.push(...row.m, ...row.i);
    m.ram.set(bytes, fa); m.ram[b] = a.h; m.ram[b + 1] = a.nf; poke16(m, b + 2, fa); m.ram[b + 4] = a.wb; poke16(m, b + 12, a.h * 2 * a.wb); addr.push(fa); fa += bytes.length;
  });
  m.ram[S.V_NINST] = insts.length;
  insts.forEach((s, i) => { const b = 0xD460 + 8 * i; m.ram[b] = s.visible ? 1 : 0; m.ram[b + 1] = s.asset; poke16(m, b + 2, s.x); poke16(m, b + 4, s.y); m.ram[b + 6] = s.frame; });
  const cp = R.castPos(pose);
  poke16(m, S.R_CS, R.cosa8(pose.a)); poke16(m, S.R_SN, R.sina8(pose.a)); poke16(m, S.R_PX, cp.x); poke16(m, S.R_PY, cp.y); poke16(m, S.VD_XMAX, mw * 256 - 1); poke16(m, S.VD_YMAX, mh * 256 - 1);
  callAt(m, S.ray_bb);
  const t = callAt(m, S.ray_bb);
  const list = R.drawList(insts, assets, pose, mw, mh), nb = m.ram[S.R_BN];
  const f = (msg) => { bad++; if (fails.length < 20) fails.push(msg); };
  if (nb !== list.length) f(`R_BN ${nb}, expected ${list.length}`);
  list.forEach(({ i, p, a, f: fr }, k) => {
    const b = S.RAY_BREC + 16 * i, got = [peek16(m, b), (peek16(m, b + 2) << 16) >> 16, m.ram[b + 4], m.ram[b + 5], m.ram[b + 6], m.ram[b + 7], peek16(m, b + 8), m.ram[b + 10], m.ram[b + 11], peek16(m, b + 12), peek16(m, b + 14)];
    const exp = [p.tx, p.L, p.wpx, p.hpx, p.hgt, p.col, addr[insts[i].asset] + fr * a.h * 2 * a.wb, a.wb, a.h, p.ustep, p.vstep];
    if (got.join() !== exp.join()) f(`record of ${i}: ${got.join()} expected ${exp.join()}`);
    if (m.ram[S.RAY_BLIST + k] !== i) f(`BLIST[${k}] = ${m.ram[S.RAY_BLIST + k]} expected ${i}`);
  });
  return t;
}

/** The case of one instance (the path it takes). */
function caseOf(s, pose, mw, mh) {
  if (!s.visible) return 'hidden';
  if (s.x > mw * 256 - 1 || s.y > mh * 256 - 1) return 'outside the map';
  const p = R.castPos(pose), cs = R.cosa8(pose.a), sn = R.sina8(pose.a), dx = s.x - p.x, dy = s.y - p.y;
  const sg = `dx${dx < 0 ? '-' : '+'} dy${dy < 0 ? '-' : '+'} cs${cs < 0 ? '-' : '+'} sn${sn < 0 ? '-' : '+'}`;
  const P = (a, c) => Math.floor(Math.abs(a) * Math.abs(c) / 256);
  const s1 = (dx < 0) !== (cs < 0), s2 = (dy < 0) !== (sn < 0), P1 = P(dx, cs), P2 = P(dy, sn);
  const tx = R.tmul(dx, cs) + R.tmul(dy, sn);
  if (tx < 64) {
    let c = `behind s1=${+s1} s2=${+s2}`;
    if (s1 && !s2) c += P2 < 64 ? ' P2<64' : ' P2>=64';
    if (!s1 && s2) c += P1 < 64 ? ' P1<64' : ' P1>=64';
    return `${c} | ${sg}`;
  }
  // hpx = 0 first, as the code before B1 tested it (before ty): B1 tests it last, so these cost more now (accepted: see the note at the end)
  const h = assets[s.asset].h, hgt = R.HGT[Math.min(tx >> 3, 1535)];
  if (((h * hgt) >> 4) === 0) return `hpx=0 h=${h}`;
  const ty = R.tmul(dy, cs) - R.tmul(dx, sn), q = R.mulP(tx), aty = Math.abs(ty);
  if ((aty >> 2) >= q) return `side off>=256 | ${sg}`;
  if (Math.floor(64 * aty / q) >= 192) return `side 192<=off<256 | ${sg}`;
  return `drawn h=${(h & (h - 1)) === 0 ? 'pow2' : 'other'} | ${sg}`;
}

const N = Number(process.argv[2] ?? 40000);
const groups = new Map();
for (let k = 0; k < N; k++) {
  assets = POOLS[k & 1];
  const mw = rr.chance(0.8) ? 32 : rr.int(4, 32), mh = rr.chance(0.8) ? 32 : rr.int(4, 32);
  const pose = { x: rr.int(0, mw * 256 - 1), y: rr.int(0, mh * 256 - 1), a: rr.int(0, 255) }, sp = rr.pick([80, 300, 1000, 3000, 9000]);
  const cp = R.castPos(pose);
  let x = cp.x + rr.int(-sp, sp), y = cp.y + rr.int(-sp, sp);
  if (rr.chance(0.03)) x = mw * 256 + rr.int(0, 300);
  const s = { visible: rr.chance(0.97) ? 1 : 0, asset: rr.int(0, assets.length - 1), frame: rr.int(0, 4), x: Math.max(0, Math.min(65535, x)), y: Math.max(0, Math.min(65535, y)) };
  const c = caseOf(s, pose, mw, mh), to = run(K.old, [s], pose, mw, mh), tn = run(K.new, [s], pose, mw, mh);
  const g = groups.get(c) ?? { n: 0, so: 0, sn: 0, maxd: -1e9, mind: 1e9, maxo: 0, maxn: 0 };
  g.n++; g.so += to; g.sn += tn; g.maxd = Math.max(g.maxd, tn - to); g.mind = Math.min(g.mind, tn - to); g.maxo = Math.max(g.maxo, to); g.maxn = Math.max(g.maxn, tn);
  groups.set(c, g);
}
const pad = (v, n) => String(v).padStart(n);
console.log(`one instance, ${N} samples (T of ray_bb, the multiplies kept; delta = after - before)`);
console.log(`${'case'.padEnd(52)} ${pad('n', 6)} ${pad('before', 7)} ${pad('after', 7)} ${pad('dmin', 6)} ${pad('dmax', 6)}`);
let worst = -1e9, worst0 = -1e9;
for (const [c, g] of [...groups].sort()) {
  if (c.startsWith('hpx=0')) worst0 = Math.max(worst0, g.maxd); else worst = Math.max(worst, g.maxd);
  console.log(`${c.padEnd(52)} ${pad(g.n, 6)} ${pad(Math.round(g.so / g.n), 7)} ${pad(Math.round(g.sn / g.n), 7)} ${pad(g.mind, 6)} ${pad(g.maxd, 6)}`);
}
// the summary per case without the signs
const coarse = new Map();
for (const [c, g] of groups) {
  const k = c.split(' | ')[0].replace(/ P[12][<>]=?64/, (m) => m);
  const h = coarse.get(k) ?? { n: 0, so: 0, sn: 0, maxd: -1e9, maxo: 0, maxn: 0 };
  h.n += g.n; h.so += g.so; h.sn += g.sn; h.maxd = Math.max(h.maxd, g.maxd); h.maxo = Math.max(h.maxo, g.maxo); h.maxn = Math.max(h.maxn, g.maxn); coarse.set(k, h);
}
console.log('\nper case (all signs): n, mean before, mean after, worst before, worst after, largest delta');
for (const [c, h] of [...coarse].sort()) console.log(`${c.padEnd(40)} ${pad(h.n, 6)} ${pad(Math.round(h.so / h.n), 7)} ${pad(Math.round(h.sn / h.n), 7)} ${pad(h.maxo, 7)} ${pad(h.maxn, 7)} ${pad(h.maxd, 6)}`);
// several instances: the whole ray_bb (projection and sort)
let mworst = -1e9, mworst0 = -1e9, m0n = 0, msum = [0, 0];
const M = Math.max(1, N >> 3);
for (let k = 0; k < M; k++) {
  assets = POOLS[k & 1];
  const mw = 32, mh = 32, pose = { x: rr.int(0, 8191), y: rr.int(0, 8191), a: rr.int(0, 255) }, sp = rr.pick([300, 1000, 3000]);
  const insts = [];
  for (let i = 0, n = rr.int(2, 16); i < n; i++) {
    let x = pose.x + rr.int(-sp, sp), y = pose.y + rr.int(-sp, sp);
    if (i && rr.chance(0.2)) { x = insts[i - 1].x; y = insts[i - 1].y; }
    insts.push({ visible: rr.chance(0.9) ? 1 : 0, asset: rr.int(0, assets.length - 1), frame: rr.int(0, 4), x: Math.max(0, Math.min(65535, x)), y: Math.max(0, Math.min(65535, y)) });
  }
  const to = run(K.old, insts, pose, mw, mh), tn = run(K.new, insts, pose, mw, mh);
  if (insts.some((s) => caseOf(s, pose, mw, mh).startsWith('hpx=0'))) { m0n++; mworst0 = Math.max(mworst0, tn - to); } else mworst = Math.max(mworst, tn - to);
  msum[0] += to; msum[1] += tn;
}
console.log(`\n${M} scenes of 2..16 instances: mean before ${Math.round(msum[0] / M)}, after ${Math.round(msum[1] / M)}, largest delta ${mworst} (${m0n} scenes with an hpx = 0 instance: largest delta ${mworst0})`);
console.log(`\none instance: largest delta ${worst} over every case but hpx = 0 (hpx = 0: ${worst0}); reference mismatches ${bad}`);
// hpx = 0 (a source under 16 rows far away: h < 8 beyond 3 cells, h = 8 beyond 24) is the one case B1 makes slower: the code before tested it right
// after tx, B1 tests it after ty and off.  Testing it early again would cost every far instance 70-130 T for a case no game has (Vaults' smallest
// billboards are 8 rows); it stays below the drawn path's cost, so the worst instance and the worst scene are still lower than before.  Accepted
// (main thread, 2026-11-11): it is reported, not failed.
for (const f of fails) console.log('  ' + f);
process.exitCode = bad || worst > 0 || mworst > 0 ? 1 : 0;
